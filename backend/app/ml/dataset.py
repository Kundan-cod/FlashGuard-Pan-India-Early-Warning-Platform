"""
Deterministic SIMULATED training-data generator (master prompt sections 5, 6, 67).

*** SIMULATED DATA — NOT REAL OBSERVATIONS, NOT GOVERNMENT DATA ***

This produces a reproducible, clearly-labelled synthetic dataset so the training
pipeline can be built and PROVEN end-to-end WITHOUT any external credentials or
verified historical labels. It is NOT a scientific ground truth.

Design goals:
  * Deterministic: a fixed seed => identical dataset every run, so tests and
    metrics are reproducible (section 66).
  * Physically ordered: labels follow well-known qualitative relationships
    (more rain + wetter soil + rising river + steeper slope => more likely
    flood; a steep susceptible slope UNDER a rain/soil trigger => more likely
    landslide). This lets a real learner actually learn something, so metrics
    are meaningful as a PIPELINE proof — not as a claim about the real world.
  * Honest labels: labels are generated by a probabilistic rule + noise, so the
    problem is non-trivial (no model can hit 100%). Every sample carries
    `is_synthetic=True`.

When verified historical labels (GSI inventory, India Flood Inventory, etc.)
are connected, THIS module is the only thing that gets replaced — the trainer,
model, schema, and inference path stay exactly the same.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

from app.ml.schema import get_schema

# A fixed generator label so no downstream artifact can lose the SIMULATED tag.
DATASET_SOURCE = "SIMULATED"
DATASET_VERSION = "sim-v1"


@dataclass
class Dataset:
    hazard: str
    feature_names: list
    X: list                   # list[list[float]] rows in schema order
    y: list                   # list[int] 0/1 or -1 (unknown)
    source: str = DATASET_SOURCE
    version: str = DATASET_VERSION
    is_synthetic: bool = True
    timestamps: list | None = None   # list[str] ISO timestamps for temporal splitting
    spatial_ids: list | None = None  # list[str|int] location IDs for spatial splitting
    metadata: dict | None = None

    def __len__(self) -> int:
        return len(self.y)

    def filter_labeled_only(self) -> "Dataset":
        """Filter out unknown (-1) samples.
        Honesty rule (section 6): unknown/unobserved events must NEVER be silently
        converted into negative (0) samples. Only confirmed 1 and confirmed 0 enter
        training/evaluation.
        """
        filtered_X, filtered_y = [], []
        filtered_ts = [] if self.timestamps is not None else None
        filtered_sp = [] if self.spatial_ids is not None else None

        for idx, label in enumerate(self.y):
            if label in (0, 1):
                filtered_X.append(self.X[idx])
                filtered_y.append(label)
                if filtered_ts is not None:
                    filtered_ts.append(self.timestamps[idx])
                if filtered_sp is not None:
                    filtered_sp.append(self.spatial_ids[idx])

        return Dataset(
            hazard=self.hazard,
            feature_names=self.feature_names,
            X=filtered_X,
            y=filtered_y,
            source=self.source,
            version=self.version,
            is_synthetic=self.is_synthetic,
            timestamps=filtered_ts,
            spatial_ids=filtered_sp,
            metadata=self.metadata,
        )

    def split_temporal_or_block(self, ratios=(0.6, 0.2, 0.2), seed: int = 42) -> tuple:
        """Partition into Train, Validation, and Test sets.
        Avoids temporal leakage: earlier periods -> TRAIN, middle -> VAL, latest -> TEST.
        If timestamps are not present, uses a contiguous block permutation to minimize
        adjacent autocorrelation leakage.
        """
        n = len(self.y)
        if self.timestamps and len(self.timestamps) == n:
            # Strictly chronological split
            order = sorted(range(n), key=lambda i: self.timestamps[i])
        else:
            # Deterministic pseudo-temporal block split
            rng = _LCG(seed)
            # Create blocks of 10 adjacent samples
            block_size = 10
            n_blocks = math.ceil(n / block_size)
            block_indices = list(range(n_blocks))
            # Shuffle blocks rather than individual rows to preserve local structure
            shuffled_blocks = []
            pool = list(block_indices)
            while pool:
                pick = int(rng.uniform(0, len(pool)))
                shuffled_blocks.append(pool.pop(min(pick, len(pool) - 1)))
            
            order = []
            for b in shuffled_blocks:
                start = b * block_size
                order.extend(range(start, min(start + block_size, n)))

        a = int(ratios[0] * n)
        b = int((ratios[0] + ratios[1]) * n)
        return order[:a], order[a:b], order[b:]


class _LCG:
    """Tiny deterministic PRNG (linear congruential) so we don't depend on the
    global numpy RNG state and results are identical across machines/versions."""

    def __init__(self, seed: int):
        self._s = seed & 0xFFFFFFFF

    def _next(self) -> int:
        self._s = (1103515245 * self._s + 12345) & 0x7FFFFFFF
        return self._s

    def uniform(self, lo: float = 0.0, hi: float = 1.0) -> float:
        return lo + (hi - lo) * (self._next() / 0x7FFFFFFF)

    def normal(self, mu: float = 0.0, sigma: float = 1.0) -> float:
        # Box-Muller from two uniforms
        u1 = max(1e-9, self.uniform())
        u2 = self.uniform()
        z = math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)
        return mu + sigma * z


def _logistic(x: float) -> float:
    if x < -60:
        return 0.0
    if x > 60:
        return 1.0
    return 1.0 / (1.0 + math.exp(-x))


def _flood_prob(f: dict) -> float:
    # Physically-ordered generative rule (NOT the model — the thing to be learnt).
    # Coefficients + bias are tuned so the SIMULATED classes are roughly balanced
    # (~45% positive) with genuine overlap, so the learning problem is non-trivial
    # and the held-out metrics are meaningful (not a degenerate all-positive model).
    z = (-8.5
         + 0.028 * f["rain_3h"]
         + 0.007 * f["rain_24h"]
         + 0.038 * f["rain_intensity"]
         + 1.5 * f["soil_saturation_index"]
         + 0.18 * f["river_level"]
         + 1.7 * f["river_rate_of_rise_1h"]
         + 0.00028 * f["flow_accumulation"]
         + 0.014 * f["slope"]
         + 0.6 * f["susceptibility"])
    return _logistic(z)


def _landslide_prob(f: dict) -> float:
    predispose = (-2.4
                  + 0.045 * f["slope"]
                  + 0.6 * f["curvature"]
                  + 2.0 * f["susceptibility"]
                  + 0.0009 * f["relative_relief"])
    trigger = max(f["rain_3h"] / 120.0,
                  f["rain_24h"] / 300.0,
                  f["soil_saturation_index"])
    gate = 0.1 + 0.9 * trigger
    return _logistic(predispose) * gate


def _sample_flood(rng: _LCG) -> dict:
    return {
        "rain_3h": max(0.0, rng.uniform(0, 120)),
        "rain_24h": max(0.0, rng.uniform(0, 300)),
        "rain_intensity": max(0.0, rng.uniform(0, 60)),
        "soil_saturation_index": rng.uniform(0, 1),
        "river_level": rng.uniform(0, 10),
        "river_rate_of_rise_1h": rng.uniform(0, 1.5),
        "flow_accumulation": rng.uniform(0, 5000),
        "slope": rng.uniform(0, 60),
        "susceptibility": rng.uniform(0, 1),
    }


def _sample_landslide(rng: _LCG) -> dict:
    return {
        "slope": rng.uniform(0, 60),
        "curvature": rng.uniform(-1, 1),
        "susceptibility": rng.uniform(0, 1),
        "relative_relief": rng.uniform(0, 1500),
        "rain_24h": max(0.0, rng.uniform(0, 300)),
        "rain_3h": max(0.0, rng.uniform(0, 120)),
        "soil_saturation_index": rng.uniform(0, 1),
    }


def generate(hazard: str, n: int = 1200, seed: int = 42) -> Dataset:
    """Generate a deterministic SIMULATED dataset for `hazard` ('flood'|'landslide').

    Same (hazard, n, seed) => byte-identical X, y every time.
    """
    schema = get_schema(hazard)
    rng = _LCG(seed + (0 if hazard == "flood" else 1))
    sampler = _sample_flood if hazard == "flood" else _sample_landslide
    prob_fn = _flood_prob if hazard == "flood" else _landslide_prob

    X, y = [], []
    for _ in range(n):
        f = sampler(rng)
        p = prob_fn(f)
        # Bernoulli draw so classes overlap => a perfect classifier is impossible
        label = 1 if rng.uniform() < p else 0
        vec, _report = schema.validate_and_vectorize(f)
        X.append(vec)
        y.append(label)

    return Dataset(hazard=hazard, feature_names=schema.names, X=X, y=y)


